// The calibration report: writes docs/CALIBRATION.md.
//   node tools/calibrate.mjs
//
// 1. Every collectable resource's parameters, and what they imply: search
//    rate, collecting rate, whether search or handling limits it, how much a
//    typical place holds, and how much it can give for ever.
// 2. The benchmarks (tools/benchmarks.mjs): computed against expected.
// 3. Sensitivity: how much upkeep (hours a day) moves when each parameter
//    moves by 10%, as an elasticity (% change in upkeep per % change in the
//    parameter). Source the biggest ones first; the rest barely matter.

import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { RESOURCES, PLACE_HA, encounter } from '../src/data/resources.js';
import { KINDS } from '../src/data/items.js';
import { here } from '../src/items.js';
import { upkeep, TUNE } from '../src/econ.js';
import { BENCH, runBench, typicalState, PLACES } from './benchmarks.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const f2 = (x) => (!isFinite(x) ? '∞' : Math.abs(x) >= 100 ? Math.round(x).toLocaleString('en') : Math.abs(x) >= 10 ? x.toFixed(1) : x.toFixed(2));
const out = [];
out.push('# Calibration', '', 'Generated by `node tools/calibrate.mjs`; do not edit by hand. Parameters live in `src/data/resources.js` (resources), `src/econ.js` (`TUNE`) and `src/data/items.js`. Every value is a judgment call unless a basis is given; the benchmarks below are what keeps them honest.', '');

// ---- 1. resources
out.push('## Resources', '', `Collecting rate = a·D / (1 + a·D·h), Holling's disc equation: a = speed × sweep width (hectares searched per hour), D = units per hectare, h = handling time per unit. A place is ${PLACE_HA} ha. "Limited by" says which term dominates at full abundance: search (scarce things) or handling (common things).`, '');
out.push('| Resource | Unit | Density /ha | Sweep m | Speed km/h | Handle min | Searched ha/h | Rate /h at full | Limited by | Full place holds | Regrows per day (max) | Note |', '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |');
for (const [id, def] of Object.entries(RESOURCES)) {
  const f = def.find;
  if (!f || !def.gather) continue;
  const k = KINDS[def.gather.kind], a = (f.speed * f.sweep) / 10, rate = encounter(def, f.density);
  const aDh = a * f.density * (f.handle / 60);
  const msy = 1.06 * def.regen * def.cap;
  out.push(`| ${def.name} | ${k.unit === 'ea' ? k.name : k.unit + ' ' + k.name} | ${f2(f.density)} | ${f.sweep} | ${f.speed} | ${f.handle} | ${f2(a)} | ${f2(rate)} | ${aDh > 1 ? 'handling' : 'search'} (${f2(aDh)}) | ${f2(def.cap)} | ${msy ? f2(msy) : '—'} | ${f.why || ''} |`);
}
out.push('', 'The number after "handling"/"search" is a·D·h: above 1, handling dominates. Densities are year-averaged; seasons would replace that with a calendar.', '');

// ---- 2. benchmarks
out.push('## Benchmarks', '', 'Whole-task times at a synthetic typical place (every resource the environment supports, at its expected amount and mean quality, all known). `npm test` fails if any is out of range.', '');
out.push('| Benchmark | Place | Holding | Computed | Expected | | Basis |', '| --- | --- | --- | --- | --- | --- | --- |');
for (const b of BENCH) {
  const r = runBench(b);
  out.push(`| ${b.name} | ${b.place} | ${(b.kit || []).join(', ') || 'nothing'} | ${f2(r.v)} ${b.unit} | ${b.range[0]}–${b.range[1]} ${b.unit} | ${r.ok ? 'ok' : '**out**'} | ${b.basis} |`);
}
out.push('');

// ---- 3. sensitivity
const CASES = [['woodland', [], 'bare-handed'], ['woodland', ['cobble', 'flake', 'stalk', 'hearth_board', 'bed', 'debris_hut'], 'basic camp'], ['meadow', ['cobble', 'flake'], 'meadow, stone tools']];
const params = [];
for (const key of Object.keys(TUNE)) params.push({ name: `TUNE.${key}`, set: (m) => { const v = TUNE[key]; TUNE[key] = v * m; return () => { TUNE[key] = v; }; } });
params.push({ name: 'firewood fuel value', set: (m) => { const v = KINDS.firewood.fuel; KINDS.firewood.fuel = v * m; return () => { KINDS.firewood.fuel = v; }; } });
for (const [id, def] of Object.entries(RESOURCES)) {
  if (!def.find || !def.gather) continue;
  params.push({ name: `${id} density`, res: id, set: (m, s) => { const r = here(s).res[id]; if (!r) return () => {}; const c = r.cap, a = r.amt; r.cap *= m; r.amt *= m; return () => { r.cap = c; r.amt = a; }; } });
  params.push({ name: `${id} handling`, res: id, set: (m) => { const v = def.find.handle; def.find.handle = v * m; return () => { def.find.handle = v; }; } });
}
const rows = [];
for (const p of params) {
  const e = CASES.map(([place, kit]) => {
    const s = typicalState(place, kit);
    if (p.res && !here(s).res[p.res]) return 0;
    const u0 = upkeep(s).U, undo = p.set(1.1, s), u1 = upkeep(s).U;
    undo();
    return isFinite(u0) && isFinite(u1) ? (u1 - u0) / u0 / 0.1 : 0;
  });
  rows.push({ name: p.name, e, top: Math.max(...e.map(Math.abs)) });
}
rows.sort((a, b) => b.top - a.top);
const base = CASES.map(([place, kit]) => upkeep(typicalState(place, kit)).U);
out.push('## Sensitivity', '', `Elasticity of upkeep: the % change in hours a day per 1% change in the parameter (computed with a 10% change). Cases: ${CASES.map(([pl, , n], i) => `${n} (${pl}, ${f2(base[i])} h/day)`).join('; ')}. Largest first; parameters with no effect in any case are omitted.`, '');
out.push(`| Parameter | ${CASES.map((c) => c[2]).join(' | ')} |`, `| --- | ${CASES.map(() => '---').join(' | ')} |`);
for (const r of rows.filter((x) => x.top >= 0.005)) out.push(`| ${r.name} | ${r.e.map((x) => (Math.abs(x) < 0.005 ? '·' : (x > 0 ? '+' : '') + x.toFixed(2))).join(' | ')} |`);
out.push('', `Environments: ${Object.entries(PLACES).map(([k, v]) => `${k} ${JSON.stringify(v)}`).join('; ')}.`, '');

writeFileSync(join(root, 'docs/CALIBRATION.md'), out.join('\n'));
console.log(`wrote docs/CALIBRATION.md (${rows.filter((x) => x.top >= 0.005).length} sensitive parameters)`);
